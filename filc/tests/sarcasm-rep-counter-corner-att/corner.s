# Corner cases for the rep-string / implicit-counter interaction fixed in
# transform.luau's emitRepString: the rep's pin-in writes the count into
# physical rcx, which must not disturb a counter web (loop/jrcxz) live across
# the instruction, and must stay hardware-faithful when the count web IS a
# counter web.
#
#   fill_seed : a `rep stosq` and a `rep movsb` with a loop-counter web live
#               across them (its value is chained through the annotated call
#               between them) and several callee-saved webs live across the
#               pins, so the counter-guard scratch has real register pressure
#               to work around.
#   one_step  : the bare single-step `movsq` (the same pin path, no count)
#               under a live counter web.
#   countdown : a `rep stosb` INSIDE a `loop` body whose counter the author
#               saves by hand around the rep: the countdown must survive the
#               rep exactly as it would on a plain cpu, iteration after
#               iteration.
	.text
	.globl	fill_seed
	.type	fill_seed, @function
fill_seed:                      ;! long(ptr,ptr,long)
	endbr64
	pushq	%rbx
	pushq	%rbp
	pushq	%r12
	pushq	%r13
	pushq	%r14
	pushq	%r15
	xorl	%r14d, %r14d        # checksum accumulator
	movq	%rdi, %r12          # dst
	movq	%rsi, %r13          # src
	movq	%rdx, %r15          # n
	leaq	sbox(%rip), %rbp
	movl	$8, %ecx
.Lwarm:
	movq	0(%rbp), %r8
	movq	32(%rbp), %r9
	xorq	%r8, %r14
	xorq	%r9, %r14
	leaq	128(%rbp), %rbp
	loop	.Lwarm
	subq	$1024, %rbp
	movq	%r12, %rdi
	movq	%r13, %rsi
	movl	%r15d, %ecx
	rep	movsq               # copy n qwords src->dst
	movq	%r15, %rbx          # a second value live across the next rep
	leaq	(%r12,%r15,8), %rdi
	movl	%r15d, %ecx
	movq	%r15, %rax          # fill value = n
	rep	stosq               # fill n qwords of n at dst+8n
	movl	$3, %edi
	call	accent              ;! long(long)
	addq	%rax, %r14          # + 10
	movq	(%r12), %rax        # first qword of the copy
	addq	%rax, %r14
	movq	(%r12,%r15,8), %rax # the first fill qword (== n)
	addq	%rax, %r14
	movl	%ebx, %ecx          # keep the second live value used past the rep
	addq	%rbx, %r14
	movq	%r14, %rax
	popq	%r15
	popq	%r14
	popq	%r13
	popq	%r12
	popq	%rbp
	popq	%rbx
	ret
	.size	fill_seed, .-fill_seed

	.globl	one_step
	.type	one_step, @function
one_step:                       ;! long(ptr,ptr)
	endbr64
	pushq	%rbx
	pushq	%rbp
	pushq	%r12
	xorl	%ebx, %ebx          # checksum accumulator
	movq	%rdi, %r12          # dst
	leaq	sbox(%rip), %rbp
	movl	$8, %ecx
.Lwarm2:
	movq	0(%rbp), %r8
	xorq	%r8, %rbx
	leaq	128(%rbp), %rbp
	loop	.Lwarm2
	subq	$1024, %rbp
	movsq                        # bare single-step copy (no count; the pin
	                             # still routes the rdi/rsi/rcx webs)
	movq	(%r12), %rax        # read back the copied qword
	addq	%rax, %rbx
	movl	$4, %edi
	call	accent              ;! long(long)
	addq	%rbx, %rax          # warm + copied qword + 11
	popq	%r12
	popq	%rbp
	popq	%rbx
	ret
	.size	one_step, .-one_step

		.globl	countdown
	.type	countdown, @function
countdown:                      ;! long(ptr,ptr)
	endbr64
	pushq	%rbx
	pushq	%r12
	xorl	%eax, %eax
	movq	%rdi, %r12          # dst
	movl	$3, %ecx            # 3 iterations
.Lcd:
	movq	(%rsi), %rbx        # load a source qword
	movq	%rbx, (%r12)        # store it
	xorq	%rbx, %rax          # fold it into the checksum
	leaq	scratch(%rip), %rdi # the rep writes a scratch byte, so its rdi
	                            # advance never disturbs the data pointers
	movq	%rcx, %rbx          # the author saves the countdown by hand
	movq	$1, %rcx
	rep	stosb               # one byte into the scratch (count web is a
	                            # fresh def while the counter web is live)
	movq	%rbx, %rcx          # restore the countdown
	addq	$8, %rsi
	addq	$8, %r12
	loop	.Lcd
	addq	$11, %rax
	popq	%r12
	popq	%rbx
	ret
	.size	countdown, .-countdown


	.globl	accent
	.type	accent, @function
accent:                         ;! long(long)
	endbr64
	leaq	7(%rdi), %rax
	ret
	.size	accent, .-accent
	.data
scratch:
	.byte	0

