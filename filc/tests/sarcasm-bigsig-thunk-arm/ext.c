long ext2(long a, long b) { return a + b; }
long ext4(long a, long b, long c, long d) { return a + b + c + d; }
long ext6(long a, long b, long c, long d, long e, long f) { return a + b + c + d + e + f; }
long ext2p(long a, long *p) { return a + *p; }
long extpp(long *a, long *b) { return *a + *b; }
long extppp(long *a, long *b, long *c) { return *a + *b + *c; }
