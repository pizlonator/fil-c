/* cpuid is an x86 instruction; kCpuids feeds x86feature.h and the
   __cpu_model machinery, so the whole table is x86-only (aarch64 callers
   are compiled out; see filc_libc_start_main.c). */
unsigned kCpuids[KCPUIDS_LEN][4];

/* Runs cpuid for every leaf tracked in kCpuids.  Called once from
   __libc_start_main() (filc_libc_start_main.c). */
void __filc_init_cpuids(void) {
  static const unsigned leaves[KCPUIDS_LEN][2] = {
      {0, 0},          {1, 0},          {2, 0},           {7, 0},
      {0x80000001, 0}, {0x80000007, 0}, {0x16, 0},        {7, 1},
  };
  unsigned i;
  for (i = 0; i < KCPUIDS_LEN; ++i) {
    unsigned eax, ebx, ecx, edx;
    /* cpuid is on the Fil-Pizlonator's safe inline asm allowlist. */
    __asm__ volatile("cpuid"
                     : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx)
                     : "a"(leaves[i][0]), "c"(leaves[i][1]));
    kCpuids[i][0] = eax;
    kCpuids[i][1] = ebx;
    kCpuids[i][2] = ecx;
    kCpuids[i][3] = edx;
  }
}

/* Fil-C port: C replacement for libc/intrin/getcpuidbrand.S (raw cpuid
   assembly, which can not be compiled by Fil-C).  Used by
   GetCpuidEmulator() (-> IsGenuineBlink()); without it, anything that
   mentions IsGenuineBlink() (pledge(), unveil(), isdebuggerpresent(), ...)
   failed to link with an undefined pizlonated_GetCpuidBrand.  Same
   semantics as the .S: brand gets the 12 bytes of ebx/ecx/edx for the
   requested leaf, nul-terminated at [12]. */
void GetCpuidBrand(char brand[13], uint32_t leafid) {
  unsigned eax, ebx, ecx, edx;
  __asm__ volatile("cpuid"
                   : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx)
                   : "a"((unsigned)leafid), "c"(0));
  __builtin_memcpy(brand + 0, &ebx, 4);
  __builtin_memcpy(brand + 4, &ecx, 4);
  __builtin_memcpy(brand + 8, &edx, 4);
  brand[12] = 0;
}
