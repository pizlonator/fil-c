#!/bin/sh
# Builds the suite in Yolo-C mode: unpizlonated C compiled by the host gcc but
# linked against this repo's "yolo" glibc in pizfix/.
#
# Yolo-C binaries cannot link the pizlonated libcrypto in pizfix/ (the ABI
# slice problem), so a separately-built, unpizlonated ("yolo") OpenSSL is
# needed.  We look for one in /tmp/yolo-openssl-install by default; override
# with YOLO_OPENSSL_HOME=...  See README.md ("Yolo-C") for the recipe used to
# produce it.
#
# This script generates a CC wrapper (below) that mirrors the proven
# /tmp/yolocc recipe and then hands it to make.  The wrapper appends its
# yolo link tail AFTER the make command line, so libraries named by the
# Makefile (-lcrypto, plus -L/-rpath pointing at the yolo OpenSSL) are
# resolved first; the -rpath order therefore puts the yolo OpenSSL ahead of
# pizfix/lib, whose pizlonated libcrypto.so.3 must not shadow it at runtime.
set -e

R=$(cd "$(dirname "$0")/../.." && pwd)
YOLO_OPENSSL_HOME=${YOLO_OPENSSL_HOME:-/tmp/yolo-openssl-install}
if [ ! -f "$YOLO_OPENSSL_HOME/include/openssl/opensslv.h" ]; then
    echo "Yolo-C needs an unpizlonated OpenSSL build; the pizlonated libcrypto" >&2
    echo "in pizfix/ cannot be linked from Yolo-C." >&2
    echo "Expected one at: $YOLO_OPENSSL_HOME (override with YOLO_OPENSSL_HOME)" >&2
    echo "See README.md section 'Yolo-C' for the build recipe." >&2
    exit 1
fi
# The install usually has lib64/ (often with lib -> lib64 as a symlink); use
# whichever directory actually exists for the baked-in runtime rpath.
if [ -d "$YOLO_OPENSSL_HOME/lib64" ]; then
    YOLO_LIB=$YOLO_OPENSSL_HOME/lib64
else
    YOLO_LIB=$YOLO_OPENSSL_HOME/lib
fi

WRAPPER=$(mktemp /tmp/yolocc.XXXXXX)
{
    cat <<WRAPPER_HEADER
#!/bin/bash
# Generated by projects/simple-openssl-tests/build_yoloc.sh -- Yolo-C wrapper.
# Yolo-C = unpizlonated C compiled by the host gcc, linked against the Fil-C
# repo's yolo glibc (pizfix/lib/libyoloc.so -> libyolocimpl.so, which IS the
# full yolo libc: printf/malloc/pthread/dlopen all live in libyolocimpl.so).
#
# Modes:
#   * compile-only (-c, -E, -S, -M, -MM) or info probes (--version, -v,
#     -print-*, -dump*): plain gcc, no changes.
#   * -shared (shared lib / DSO): gcc + pizfix crtbegin.o/crtend.o (supply
#     __dso_handle for the nonshared atexit stubs) + -lyoloc + -lgcc, so the
#     .so gets DT_NEEDED libyolocimpl.so (NOT libc.so.6, which would drag the
#     host glibc into a yolo process).
#   * everything else = executable link: gcc + pizfix crt1/crti/crtn +
#     crtbegin/crtend + -lyoloc + the yolo dynamic loader + rpaths.
#
# RUNPATH order is [yolo OpenSSL, pizfix/lib]: pizfix/lib also contains the
# PIZLONATED libcrypto.so.3/libssl.so.3, which would otherwise shadow the
# yolo ones at runtime.  The Makefile's own -L/-rpath for OPENSSL_HOME come
# earlier still, so they win first.
#
# NOTE: the tail is APPENDED after "\$@" so that libraries named in "\$@"
# (e.g. -lcrypto) are resolved first; our -L/-l only catch what's left.
WRAPPER_HEADER
    printf 'R=%s\nOSSL_LIB=%s\n' "$R" "$YOLO_LIB"
    cat <<'WRAPPER_BODY'

compile_only=0
shared=0
info=0
for a in "$@"; do
  case "$a" in
    -c|-E|-S|-M|-MM)  compile_only=1 ;;
    -shared)          shared=1 ;;
    -v|--version|-print-file-name=*|-print-libgcc-file-name=*|\
    -print-prog-name=*|-print-search-dirs|-print-multiarch|\
    -dumpmachine|-dumpversion) info=1 ;;
  esac
done

if [ "$compile_only" = 1 ] || [ "$info" = 1 ]; then
  exec gcc "$@"
fi

if [ "$shared" = 1 ]; then
  exec gcc "$@" -nostdlib -nostartfiles \
    "$R/pizfix/lib/crtbegin.o" "$R/pizfix/lib/crtend.o" \
    -L"$R/pizfix/lib" -lyoloc -lgcc \
    -Wl,-rpath,"$OSSL_LIB" -Wl,-rpath,"$R/pizfix/lib"
fi

# Executable link.
err=/tmp/yolocc-link-err.$$
tail=(-nostdlib -nostartfiles
      "$R/pizfix/lib/crt1.o" "$R/pizfix/lib/crti.o" "$R/pizfix/lib/crtn.o"
      "$R/pizfix/lib/crtbegin.o" "$R/pizfix/lib/crtend.o"
      -L"$R/pizfix/lib" -lyoloc
      -Wl,--dynamic-linker="$R/pizfix/lib/ld-fil1-x86_64.so"
      -Wl,-rpath,"$OSSL_LIB" -Wl,-rpath,"$R/pizfix/lib")

if gcc "$@" "${tail[@]}" 2>"$err"; then
  rm -f "$err"; exit 0
fi
# Retry once with -lgcc in case of missing libgcc symbols (__udivti3 etc.).
if gcc "$@" "${tail[@]}" -lgcc 2>"$err"; then
  rm -f "$err"; exit 0
fi
rc=$?
cat "$err" >&2
rm -f "$err"
exit $rc
WRAPPER_BODY
} >"$WRAPPER"
chmod +x "$WRAPPER"

# Run make without exec so we can clean up the generated wrapper afterwards.
rc=0
make CC="$WRAPPER" OPENSSL_HOME="$YOLO_OPENSSL_HOME" "$@" || rc=$?
rm -f "$WRAPPER"
exit $rc
