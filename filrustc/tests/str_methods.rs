fn main() {
    let s = "The quick brown fox; the lazy dog.";
    println!("split = {}", s.split(' ').count());
    let parts: Vec<&str> = s.splitn(3, ' ').collect();
    println!("splitn = {:?}", parts);
    let rparts: Vec<&str> = s.rsplitn(2, ' ').collect();
    println!("rsplitn = {:?}", rparts);
    let matches: Vec<&str> = s.matches("the").collect();
    println!("matches(the) = {:?}", matches);
    let rmatches: Vec<&str> = s.rmatches("t").collect();
    println!("rmatches(t) = {:?}", rmatches);
    let indices: Vec<usize> = s.match_indices("a").map(|(i, _)| i).collect();
    println!("indices(a) = {:?}", indices);
    println!("trim = '{}'", "  padded  ".trim());
    println!("trim_start = '{}'", "  padded  ".trim_start());
    println!("trim_end = '{}'", "  padded  ".trim_end_matches('d'));
    println!("find = {:?} rfind = {:?}", s.find("quick"), s.rfind('o'));
    let ci: Vec<(usize, char)> = "ab\u{e9}c".char_indices().collect();
    println!("char_indices = {:?}", ci);
    let utf16: Vec<u16> = "A\u{1F600}".encode_utf16().collect();
    println!("utf16 units = {}", utf16.len());
    println!("split_ws = {}", "a  b\tc\nd".split_whitespace().count());
    println!("split_ascii_ws = {}", "a  b\tc\nd".split_ascii_whitespace().count());
    println!("strip_prefix = {:?} strip_suffix = {:?}", "file.txt".strip_prefix("file"), "file.txt".strip_suffix(".txt"));
    println!("repeat = {}", "ab".repeat(3));
    println!("replace = {}", "aaa".replace('a', "b"));
    println!("replacen = {}", "aaaa".replacen('a', "b", 2));
    println!("split_terminator = {:?}", "a;b;".split_terminator(';').collect::<Vec<_>>());
    println!("lines = {:?}", "l1\nl2\n".lines().collect::<Vec<_>>());
    println!("chars = {}", "h\u{e9}llo".chars().count());
    println!("upper = {}", "h\u{e9}llo".to_uppercase());
    println!("escaped = {}", "a\nb".escape_debug());
    let c = 'Z';
    println!("to_digit = {:?} len_utf8 = {} is_alphabetic = {}", 'F'.to_digit(16), c.len_utf8(), c.is_alphabetic());
    println!("capitalize-ish = {}{}", "hello".chars().next().unwrap().to_uppercase(), "hello"[1..].to_string());
    println!("concat str = {}", ["a", "b"].concat());
    println!("eq_ignore = {}", "HELLO".eq_ignore_ascii_case("hello"));
    println!("starts = {} ends = {}", "path/to/file".starts_with("path"), "path/to/file".ends_with("file"));
    println!("idx = {:?} bytes = {}", "hello".as_bytes()[1], "h\u{e9}".len());
    println!("from_utf8 = {:?}", std::str::from_utf8(&[104, 105]));
}
